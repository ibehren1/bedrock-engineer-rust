//! The app command list, read from the `tauri::generate_handler![...]` call in
//! `commands/mod.rs`, so the ACL can't drift from what is actually registered.
//!
//! Shared by `build.rs` (which feeds it to `tauri_build::AppManifest::commands` and writes the
//! `app-commands` permission set) and the tests in `commands/mod.rs`. Std only: `build.rs`
//! includes this file with `#[path]`.

/// The command names registered by the first `generate_handler![...]` in `source`, in order.
///
/// Items are `module::command` paths separated by commas; `//` comments are ignored. Errors on
/// a missing list, an empty list, a malformed item or a duplicate.
pub fn handler_commands(source: &str) -> Result<Vec<String>, String> {
    const OPEN: &str = "generate_handler![";
    let start = source.find(OPEN).ok_or("no generate_handler![...] found")? + OPEN.len();
    let code: String = source[start..]
        .lines()
        .map(|line| line.split("//").next().unwrap_or(""))
        .collect::<Vec<_>>()
        .join("\n");
    let body = &code[..code
        .find(']')
        .ok_or("unterminated generate_handler![...]")?];

    let mut commands: Vec<String> = Vec::new();
    for item in body.split(',').map(str::trim).filter(|s| !s.is_empty()) {
        let name = item.rsplit("::").next().unwrap_or(item).trim();
        let valid = !name.is_empty()
            && !name.starts_with(|c: char| c.is_ascii_digit())
            && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        if !valid {
            return Err(format!("unexpected generate_handler! item `{item}`"));
        }
        if commands.iter().any(|c| c == name) {
            return Err(format!("command `{name}` registered twice"));
        }
        commands.push(name.to_string());
    }
    if commands.is_empty() {
        return Err("generate_handler![...] is empty".into());
    }
    Ok(commands)
}

/// The ACL permission Tauri generates for allowing `command` (`allow-` + kebab-case).
pub fn allow_permission(command: &str) -> String {
    format!("allow-{}", command.replace('_', "-"))
}

/// Command-name prefixes only the main window may call (`capabilities/main-window.json`), so
/// they are left out of `app-commands`: the local terminal runs a real shell on the user's
/// machine, and only the chat page in the main window opens one; app updates download and
/// install a new version of the app, which only the main window's Settings and banner drive;
/// knowledgebase commands read files from any path the caller names (agent editor and
/// Settings only); usage commands read the whole spending history (Accounting page only);
/// Docker sandbox commands run commands (and open a root shell) in a container that has the
/// project folder mounted, which only the chat page and Settings drive.
pub const MAIN_WINDOW_ONLY_PREFIXES: &[&str] = &[
    "local_terminal_",
    "app_update_",
    "knowledge_",
    "usage_",
    "docker_sandbox_",
];

/// Single commands only the main window may call, on top of the prefixes: tool execution runs
/// host commands and every other built-in tool, and settings writes can rewrite agents (their
/// command allowlists, MCP servers) and credentials. The task history and file viewer windows
/// only read settings.
pub const MAIN_WINDOW_ONLY_COMMANDS: &[&str] = &[
    "tools_execute",
    "bedrock_execute_tool",
    "store_set",
    "store_delete",
];

/// Commands that live in a main-window-only module but are deliberately granted to every
/// full-UI window. Anything else defined in those modules must match a main-window-only
/// prefix, so a command named off-prefix can't slip into `app-commands` unnoticed.
#[allow(dead_code)] // read by commands/acl_tests.rs, not build.rs
pub const MAIN_WINDOW_MODULE_EXCEPTIONS: &[&str] = &[
    // Per-chat cost badge, shown in the task history window too.
    "session_usage_costs",
];

pub fn is_main_window_only(command: &str) -> bool {
    MAIN_WINDOW_ONLY_COMMANDS.contains(&command)
        || MAIN_WINDOW_ONLY_PREFIXES
            .iter()
            .any(|prefix| command.starts_with(prefix))
}

/// `permissions/app-commands.toml`: one set, `app-commands`, allowing every command except the
/// main-window-only ones.
pub fn all_commands_set(commands: &[String]) -> String {
    let mut out = String::from(
        "# Generated by build.rs from the generate_handler! list in src/commands/mod.rs.\n\
         # Do not edit: add commands to that list instead.\n\n\
         [[set]]\n\
         identifier = \"app-commands\"\n\
         description = \"Every app command (commands::handler()) except the main-window-only ones.\"\n\
         permissions = [\n",
    );
    for command in commands.iter().filter(|c| !is_main_window_only(c)) {
        out.push_str(&format!("  \"{}\",\n", allow_permission(command)));
    }
    out.push_str("]\n");
    out
}

/// `permissions/main-window-commands.toml`: one set, `main-window-commands`, allowing the
/// main-window-only commands.
pub fn main_window_commands_set(commands: &[String]) -> String {
    let mut out = String::from(
        "# Generated by build.rs from the generate_handler! list in src/commands/mod.rs.\n\
         # Do not edit: add commands to that list instead.\n\n\
         [[set]]\n\
         identifier = \"main-window-commands\"\n\
         description = \"App commands only the main window may call (see MAIN_WINDOW_ONLY_PREFIXES / MAIN_WINDOW_ONLY_COMMANDS in src/command_list.rs).\"\n\
         permissions = [\n",
    );
    for command in commands.iter().filter(|c| is_main_window_only(c)) {
        out.push_str(&format!("  \"{}\",\n", allow_permission(command)));
    }
    out.push_str("]\n");
    out
}
